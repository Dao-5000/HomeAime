        "【关键】表情包/点歌/[ACTION] 必须写标记才生效——光说「发一张给你」发不出图；"
        "控制电脑/手机类例外：TA 直说命令（「打开微信」「音量调到50」）系统已自动执行，"
        "你自然接话即可，别说「我帮你打开了」。不确定能否做某事，先看这份清单，"
        "不要凭空说「我做不到」或「我已经做了」。"

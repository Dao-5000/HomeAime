# -*- coding: utf-8 -*-
"""
AI 能力清单（方案 A+B）：统一、持久化、按配置动态生成的「我现在能做什么」常驻注入块。

解决「模型看不到自己有什么功能」的根因：
  1. 常驻 —— 放在 system prompt 高位，不受 _MAX_EXTRA_CHARS 从末尾裁剪的影响；
  2. 动态 —— 按当前实际配置（视觉 key / 感知开关 / 游戏连接等）生成，模型看到的是
     「你现在真正能用的」，而不是「你可能有的」；
  3. 统一 —— App / QQ / 主动消息等所有入口都从这一个模块拿能力清单，不再各自散落一段
     prompt（之前表情包/点歌/动作分别写在 chat_logic / onebot / generator 三处）。

新增能力：在 get_capabilities() 里加一条即可，所有入口自动生效。
"""
from . import config


def get_capabilities() -> list:
    """返回当前可用能力列表，每项 {name, usage}。usage 是给模型看的「怎么用」。

    顺序即优先级：越靠前的越重要、越不容易被忽略。
    """
    caps = []

    # 1. 表情包（有素材就可用）
    try:
        from . import sticker_manager as _sm
        if _sm.list_stickers():
            caps.append({
                "name": "发表情包",
                "usage": "回复里单独一行写 [sticker:文件名] 即可发一张表情包图；写中文情绪（如 [sticker:开心]）也能被识别成对应图片。光说「发一张给你」不算发。",
            })
    except Exception:
        pass

    # 2. 定时提醒 / 待办 / 约定（始终可用）
    #   ★ 2026-09-16（定时提醒误触发修复配套）：措辞从「功能清单」改成「你的判断责任」。
    #     用户原话：「模型需要知道她有判断这个能力，不然以为在普通聊天」。
    #     事故背景：用户说「哎呀再等我会哈 到时候聊到两点半吧」，她只当普通闲聊附和，
    #     而系统侧的正则把「到时候」当委托、抽出残尾「半吧」建了个 02:00 的提醒。
    #     所以这条能力必须同时说清两件事：**是委托就归你判断+记下**，
    #     **是闲聊就别硬记**——判断权在她，系统只负责兜底与校时。
    caps.append({
        "name": "定时提醒",
        "usage": "宝说「X 点提醒我」「记得叫我做某事」「以后每天几点提醒我」时，"
                 "**这是你要自己判断、也要自己负责的事**（不是普通闲聊）：他哪怕说得很随意、"
                 "没写「提醒」两个字（例如「到时候聊到两点半吧」「两点半叫我」「明天早上喊我」），"
                 "只要是在跟你约定一个时间点上的事，就当成委托/约定记下来、到点做到，别只在嘴上答应；"
                 "反过来，纯闲聊里出现时间词（如「我昨天两点才睡」）就不是委托，不要硬记成提醒。"
                 "拿不准就问一句「要我几点提醒你什么？」。",
    })

    # 3. 控制 TA 的电脑（QQ 文字指令 / F9 按住说话 都直接执行，无需标记）
    caps.append({
        "name": "控制 TA 的电脑",
        "usage": "TA 说「打开微信/记事本/计算器/B站」「音量调到 50」「下一首」「暂停」「帮我输入 XXX」"
                 "「读一下我复制的内容」「显示桌面」「锁屏」「看看我的屏幕」等，系统会**直接执行**——"
                 "这类明确指令你不用写任何标记，自然接话就好（别再说「我帮你打开了」，系统已经做了）。"
                 "「10 分钟后关机」这类大动作系统会先向 TA 语音确认。"
                 "你想主动贴心操作时才写 [ACTION]{\"type\":\"open_app\",\"app\":\"音乐\"}[/ACTION]。",
    })

    # 3.5 控制 TA 的手机（iOS 快捷指令）
    caps.append({
        "name": "控制 TA 的手机",
        "usage": "TA 说「在手机上打开抖音/B站/微信」时走 iOS 快捷指令，系统自动处理，你自然接话。"
                 "设备区分：主人没说「手机」的控制指令都是指电脑。",
    })

    # 4. 点歌（音乐分享）
    caps.append({
        "name": "点歌",
        "usage": "TA 想听歌时，回复最后单独一行写 [SONG]歌名 歌手[/SONG]，会以音乐卡片发给 TA。",
    })

    # 5. 语音回复（TTS 默认可用，本地 CosyVoice / edge-tts 兜底）
    try:
        if config.tts_provider() or True:
            caps.append({
                "name": "发语音",
                "usage": "TA 说想听你声音时，可以发语音条。",
            })
    except Exception:
        pass

    # 6. 看图（有视觉 Key 才可用）
    try:
        if config.vision_key():
            caps.append({
                "name": "看图",
                "usage": "TA 发图片时，你能看懂图里的文字和内容并回应。",
            })
    except Exception:
        pass

    # 7. 感知 TA 状态（感知总开关开启才可用）
    try:
        if config.get("AWARENESS_ENABLED"):
            caps.append({
                "name": "感知 TA 状态",
                "usage": "能知道 TA 当前在用哪个应用、是否在忙（陪伴模式下可自然说给 TA 听）。",
            })
    except Exception:
        pass

    # 8. 游戏陪伴（Minecraft 大脑在线时才可用；用模块级单例同步判断，避免 await）
    try:
        from .minecraft import game_bridge as _gb_mod
        _gb = getattr(_gb_mod, "_brain", None)
        if _gb is not None and getattr(_gb, "ready", False):
            caps.append({
                "name": "游戏里陪 TA（Minecraft）",
                "usage": "骨子现在正在 Minecraft 里陪 TA 玩，游戏里的状态（位置/在做什么）和聊天是同一情境。",
            })
    except Exception:
        pass

    # 9. 星露谷陪伴（StardewValley-MCP 就绪且游戏在线时才可用；同步读单例属性避免 await）
    try:
        from .stardew import game_bridge as _sb_mod
        _sb = getattr(_sb_mod, "_brain", None)
        if _sb is not None and getattr(_sb, "ready", False) and getattr(_sb, "_game_online", False):
            caps.append({
                "name": "星露谷农场陪 TA",
                "usage": "骨子现在正在主人的星露谷农场里，可以一起种田、钓鱼、探矿；TA 在 QQ 说「浇水/收菜/去钓鱼/跟着我」就能指挥你行动。",
            })
    except Exception:
        pass

    return caps


def build_capability_block() -> str:
    """生成「能力清单」常驻注入块（紧凑、高优先级、强调『说≠做』）。"""
    caps = get_capabilities()
    if not caps:
        return ""
    lines = ["【你现在具备的能力（真实可用，不是口头承诺）】"]
    for c in caps:
        lines.append(f"- {c['name']}：{c['usage']}")
    lines.append(
        "【关键】需要标记的能力（表情包/点歌/[ACTION] 主动动作），必须写对应标记才真正生效；"
        "但**控制电脑/手机类指令例外**——TA 直接说命令（「打开微信」「音量调到50」）时系统已自动执行，"
        "你自然接话即可，千万别再说「我帮你打开了」这种话（事情已经做完了）。"
        "不确定自己能不能做某事时，先看这份清单，不要凭空说「我做不到」或「我已经做了」。"
    )
    return "\n".join(lines)


